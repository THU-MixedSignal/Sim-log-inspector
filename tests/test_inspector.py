import hashlib
import json
import re
import sqlite3
import tempfile
import unittest
from pathlib import Path

from simcheck.parser import initial, parse, quantity
from simcheck.store import (SchemaError, connect, events, evidence, manifest, measurements,
                            open_readonly, problem_groups, scan, snapshot)

FIX = Path(__file__).parent / 'fixtures'
FOOT = 'spectre completes with 0 errors, 0 warnings, and 0 notices.\n'


def all_events(db, run=None):
    out, after = [], 0
    while True:
        chunk = events(db, run, after, 500)
        if not chunk:
            return out
        out += chunk
        after = chunk[-1]['event_id']


def brief(db, run):
    return next(r for r in snapshot(db)['runs'] if r['run_id'] == run)


class RealLogs(unittest.TestCase):
    # Golden facts reviewed against native excerpts, not generated by the parser:
    # status, R4MEAS frames, native "N warnings suppressed" total, printed CMI messages.
    GOLD = {'a_fft': ('complete', 1032, 253, 0), 'b_fft': ('complete', 1032, 24032780, 25),
            'noise': ('complete', 1032, 21700496, 25), 'static': ('complete', 285, 24228142, 25),
            'minstep': ('failed', 0, None, 0), 'compile': ('failed', 0, None, 0),
            'output_limit': ('failed', 0, None, 25), 'license': ('failed', 0, None, 0)}
    # Real raw/logStatus per run: (analysis, latest state). compile and license stopped before
    # Spectre created raw/, so the manifest points at a file that does not exist.
    LOG_STATUS = {'a_fft': ('tran_perf', 'PASS'), 'b_fft': ('tran_perf', 'PASS'),
                  'noise': ('tran_perf', 'PASS'), 'static': ('tran_perf', 'PASS'),
                  'minstep': ('tran_test', 'FAIL'), 'output_limit': ('tran_test', 'FAIL'),
                  'compile': ('tran_test', None), 'license': ('tran_test', None)}

    def test_provenance(self):
        for name, meta in json.loads((FIX / 'provenance.json').read_text(encoding='utf-8')).items():
            data = (FIX / (name + '.log')).read_bytes()
            self.assertEqual(hashlib.sha256(data).hexdigest(), meta['fixture_sha256'], name)
            # License server addresses (port@host) are redacted from every fixture.
            self.assertIsNone(re.search(rb'\d+@[A-Za-z]', data), name)
            status = FIX / (name + '.logStatus')
            if 'fixture_sha256' in meta['log_status']:
                self.assertEqual(hashlib.sha256(status.read_bytes()).hexdigest(), meta['log_status']['fixture_sha256'])
            else:
                self.assertFalse(status.exists(), name)

    def test_all_real_logs(self):
        for name, (status, frames, suppressed, cmi) in self.GOLD.items():
            with self.subTest(name=name), tempfile.TemporaryDirectory() as tmp:
                with connect(Path(tmp) / 'db') as db:
                    analysis, last_status = self.LOG_STATUS[name]
                    c = {'id': name, 'log': str(FIX / (name + '.log')), 'state': str(FIX / (name + '.state.json')),
                         'log_status': str(FIX / (name + '.logStatus')), 'analysis': analysis}
                    r = scan(db, c)
                    self.assertEqual(r['integrity']['status'], status)
                    check = r['integrity']['checks'][1]
                    if last_status:
                        self.assertEqual((check['status'], check['last_status']), ('observed', last_status))
                    else:
                        self.assertEqual(check['status'], 'unavailable')
                    self.assertEqual(r['parser']['frames'], frames)
                    self.assertEqual(r['parser']['suppressed_totals'].get('warning'), suppressed)
                    stored = all_events(db, name)
                    self.assertEqual(sum((e.get('code') or '').startswith('CMI-') for e in stored), cmi)
                    footer = r['parser']['footer']
                    if footer:
                        # Spectre's footer counts printed messages; our tagged messages must agree.
                        messages = [e for e in stored if e['kind'] == 'native_message']
                        self.assertEqual(sum(e['severity'] == 'WARNING' for e in messages), footer['warnings'])
                        self.assertEqual(sum(e['severity'] in ('ERROR', 'FATAL') for e in messages),
                                         footer['errors'])
                    if name in ('b_fft', 'noise'):
                        s = r['parser']['settings']
                        self.assertEqual(s['None:requested:method']['value'], 'gear2only')
                        self.assertEqual(s['tran_perf:effective:method']['value'], 'trap')
                    before = db.execute('SELECT count(*) FROM events').fetchone()[0]
                    scan(db, c)
                    self.assertEqual(db.execute('SELECT count(*) FROM events').fetchone()[0], before)
                    summary = brief(db, name)
                    self.assertEqual(summary['state']['status'], status)
                    self.assertNotIn('parser', summary)
                    self.assertNotIn('raw', json.dumps(summary['measurements']))
                    self.assertEqual(summary['measurements']['records'], frames)
                    groups = problem_groups(db, name, limit=500)
                    self.assertEqual(sum(g['printed_count'] for g in groups if g['problem_key'].startswith('CMI-')), cmi)
                    text = (FIX / (name + '.log')).read_text(encoding='utf-8')
                    for g in groups:
                        e = evidence(db, g['first_evidence_id'])
                        self.assertIn(e['raw'], text)
                        if 'header' in e:
                            self.assertIn(e['header']['raw'], text)

    def test_voltage_time_and_location(self):
        s = initial()
        out = []
        for n, line in enumerate((FIX / 'noise.log').read_text(encoding='utf-8').splitlines(), 1):
            out += parse(line, s, n)
        e = next(e for e in out if e.get('code') == 'CMI-2754')
        self.assertEqual(e['terminal'], 'Vgd')
        self.assertAlmostEqual(e['measured']['value_si'], -.991867)
        self.assertAlmostEqual(e['limit']['value_si'], .990)
        self.assertAlmostEqual(e['sim_time_s'], 60.0961e-9)
        self.assertEqual(e['analysis'], 'tran_perf')
        self.assertAlmostEqual(e['analysis_stop_s'], 103.259e-6)


class Boundaries(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.p = Path(self.tmp.name)
        self.log = self.p / 'spectre.out'
        self.log.write_bytes(b'')
        self.db = connect(self.p / 'events.db')
        self.c = {'id': 'test', 'log': str(self.log)}

    def tearDown(self):
        self.db.close()
        self.tmp.cleanup()

    def write(self, text):
        self.log.write_text(text, encoding='utf-8')

    def test_units_and_defaults(self):
        self.assertEqual(quantity('10 ps')['value_si'], quantity('1e-11 s')['value_si'])
        s = initial()
        a = parse(' maxstep = 10 ps, default 35.59 ns', s, 1)[0]
        b = parse(' maxstep = 10 ps, default 325.59 ns', s, 2)[0]
        self.assertEqual(a['normalized'], b['normalized'])
        self.assertNotEqual(a['default_text'], b['default_text'])

    def test_state_before_log_exists(self):
        self.log.unlink()
        state = self.p / 'state.json'
        self.c['state'] = str(state)
        for reported in ('queued', 'submitted', 'waiting', 'starting'):
            state.write_text(json.dumps({'status': reported}), encoding='utf-8')
            result = scan(self.db, self.c)
            self.assertEqual(result['integrity']['status'], reported)
            self.assertIsNone(result['error'])
        state.write_text('{"status":"rejected","reason":"queue_timeout"}', encoding='utf-8')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'failed')
        state.write_text('{"status":"complete","exit_code":0}', encoding='utf-8')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')
        del self.c['state']
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'unknown')

    def test_configured_empty_state_cannot_confirm_completion(self):
        self.write(FOOT)
        state = self.p / 'state.json'
        self.c['state'] = str(state)
        for invalid in ({}, {'status': 'unrecognized'}, {'status': []}):
            state.write_text(json.dumps(invalid))
            result = scan(self.db, self.c)['integrity']
            self.assertEqual(result['status'], 'incomplete')
            self.assertEqual(result['checks'][0]['status'], 'unknown')
        state.write_text('{"status":"complete","exit_code":0}')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'complete')

    def test_older_cached_state_is_checked_without_modifying_the_snapshot(self):
        self.write(FOOT)
        scan(self.db, self.c)
        row = self.db.execute('SELECT summary FROM runs WHERE id=?', (self.c['id'],)).fetchone()
        stored = json.loads(row[0])
        state = stored['integrity']['checks'][0]
        state.update(status='observed', reported_status='unknown')
        original = json.dumps(stored)
        self.db.execute('UPDATE runs SET summary=?', (original,))
        self.db.commit()
        result = brief(self.db, self.c['id'])
        self.assertEqual(result['state']['status'], 'incomplete')
        self.assertEqual(self.db.execute('SELECT summary FROM runs').fetchone()[0], original)

    def test_stop_metadata_without_raw_is_not_a_missing_raw_file(self):
        self.write(FOOT)
        self.c['expected_stop_s'] = 20e-9
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'complete')
        self.c['raw'] = str(self.p / 'not-created.tran')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')

    def test_failure_summary_does_not_rewind_logged_progress(self):
        s = initial()
        parse("Transient Analysis `tran_live': time = (0 s -> 20 ns)", s, 1)
        parse("Error found by spectre at time = 5.00081 ns during transient analysis `tran_live'.", s, 2)
        parse(' Top 2 Solution Convergence failure counts accumulated from time = 0 s to time = 5.00081 ns of analysis:', s, 3)
        self.assertAlmostEqual(s['last_time_s'], 5.00081e-9)
        parse("Transient Analysis `another': time = (0 s -> 10 ns)", s, 4)
        self.assertIsNone(s['last_time_s'])

    def test_progress_prefix_before_explicit_tb_fail(self):
        s = initial()
        fail = parse('......9......8......7......6...FAIL,intentional_testbench_report', s, 1)
        self.assertEqual(fail[0]['problem_key'], 'TB:reported_FAIL')
        self.assertEqual(fail[0]['severity'], 'INFO')
        passed = parse('......9......8...PASS,intentional_testbench_report', s, 2)
        self.assertNotIn('problem_key', passed[0])
        self.assertEqual(parse('ordinary sentence FAIL,not a TB record', s, 3), [])

    def test_bytewise_and_unicode(self):
        text = ("Warning from spectre at time = 2 ns during transient analysis `tran'.\n"
                ' WARNING (NEW-99): 这是 µV\n' + FOOT)
        for b in text.encode():
            with self.log.open('ab') as f:
                f.write(bytes([b]))
            scan(self.db, self.c)
        incremental = [e['raw'] for e in events(self.db, 'test')]
        s = initial()
        expected = [e['raw'] for i, l in enumerate(text.splitlines(), 1) for e in parse(l, s, i)]
        self.assertEqual(incremental, expected)

    def test_partial_line(self):
        self.write('ERROR (TEST-1): unfinished')
        r = scan(self.db, self.c)
        self.assertTrue(r['integrity']['pending_partial_line'])
        self.assertEqual(events(self.db), [])
        r = scan(self.db, self.c, final=True)
        self.assertEqual(r['integrity']['status'], 'failed')

    def test_restart_cursor(self):
        self.write('WARNING (X-1): first\n')
        scan(self.db, self.c)
        self.db.close()
        self.db = connect(self.p / 'events.db')
        scan(self.db, self.c)
        self.assertEqual(len(events(self.db)), 1)

    def test_truncation_retains_history(self):
        self.write('WARNING (X-1): ' + 'a' * 100 + '\n')
        scan(self.db, self.c)
        self.write('ERROR (Y-2): new\n')
        r = scan(self.db, self.c)
        self.assertEqual(r['generation'], 2)
        self.assertEqual(len(events(self.db)), 2)

    def test_same_size_replacement(self):
        self.write('WARNING (X-1): a\n')
        scan(self.db, self.c)
        self.write('WARNING (X-2): b\n')
        self.assertEqual(scan(self.db, self.c)['generation'], 2)

    def test_appended_attempt(self):
        self.write('Spectre (R) Circuit Simulator\n' + FOOT)
        scan(self.db, self.c)
        with self.log.open('a') as f:
            f.write('Spectre (R) Circuit Simulator\nERROR (X-2): failed\n')
        r = scan(self.db, self.c)
        self.assertEqual(r['generation'], 2)
        self.assertEqual(r['integrity']['status'], 'failed')

    def test_fatal_exit_zero(self):
        # Native layout: the uncoded FATAL is indented under Spectre's own header line.
        self.write('Fatal error found by spectre during topology check.\n    FATAL: Internal error\n' + FOOT)
        state = self.p / 'state'
        state.write_text('{"status":"limit_exceeded","exit_code":0,"reason":"output_size_limit"}')
        self.c['state'] = str(state)
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'failed')

    def test_log_status_latest_transition_wins(self):
        # Real logStatus files are START -> PASS/FAIL transition logs per analysis.
        self.write(FOOT)
        status = self.p / 'status'
        self.c.update(log_status=str(status), analysis='tran')
        for body, expected in (('t0\ttran\tSTART\nt1\ttran\tPASS\n', 'complete'),
                               ('t0\tdc\tPASS\nt1\ttran\tPASS\nt2\ttran\tFAIL\n', 'failed'),
                               ('t0\ttran\tSTART\n', 'incomplete')):
            status.write_text(body)
            self.assertEqual(scan(self.db, self.c)['integrity']['status'], expected, body)

    def test_wrong_analysis_not_pass(self):
        self.write(FOOT)
        status = self.p / 'status'
        status.write_text('now\tdc\tPASS\n')
        self.c.update(log_status=str(status), analysis='tran')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')

    def test_running_not_terminated(self):
        state = self.p / 'state'
        state.write_text('{"status":"running"}')
        self.c['state'] = str(state)
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'running')

    def test_no_footer_unknown(self):
        self.write('WARNING (X-1): information\n')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'unknown')

    def test_raw_end_and_stop(self):
        self.write(FOOT)
        raw = self.p / 'wave'
        raw.write_text('HEADER\nVALUE\n"time" 1e-9\nEND\n')
        self.c.update(raw=str(raw), expected_stop_s=2e-9)
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')
        self.c['expected_stop_s'] = 1e-9
        r = scan(self.db, self.c)
        self.assertEqual(r['integrity']['status'], 'complete')
        self.assertEqual(r['integrity']['checks'][2]['size_bytes'], raw.stat().st_size)
        raw.write_text('HEADER\nVALUE\n"time" 1e-9\n')
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')

    def test_unsupported_raw(self):
        self.write(FOOT)
        raw = self.p / 'wave'
        raw.write_bytes(b'\x00binary')
        self.c['raw'] = str(raw)
        self.assertEqual(scan(self.db, self.c)['integrity']['status'], 'incomplete')

    def test_oversized_line(self):
        self.write('x' * 200000 + '\n' + FOOT)
        r = scan(self.db, self.c)
        self.assertEqual(r['integrity']['status'], 'incomplete')
        self.assertEqual(sum(e['kind'] == 'line_size_limit' for e in events(self.db)), 1)

    def test_manifest_validation(self):
        m = self.p / 'm.json'
        bad = ['{"runs":[{"id":"a","log":"x"},{"id":"a","log":"y"}]}',
               '{"runs":[{"id":"a","log":"x"}],"watch":[{"name":"no matcher"}]}',
               '{"runs":[{"id":"a","log":"x","baseline":"missing"}]}',
               '{"runs":[{"id":"a","log":"x","watch":[{"name":"x","code":"A*","oops":1}]}]}']
        for text in bad:
            m.write_text(text)
            with self.assertRaises(ValueError, msg=text):
                manifest(m)
        m.write_text('{"baseline":"a","watch":[{"name":"r","code":"X-*"}],'
                     '"runs":[{"id":"a","log":"x"},{"id":"b","log":"y","quiet_after_s":60}]}')
        runs = {r['id']: r for r in manifest(m)['runs']}
        self.assertIsNone(runs['a']['baseline'])
        self.assertEqual(runs['b']['baseline'], 'a')
        self.assertEqual(runs['b']['quiet_after_s'], 60)
        self.assertEqual(runs['a']['watch'][0]['name'], 'r')

    def test_unknown_code_preserved(self):
        self.write('WARNING (FUTURE-999): unknown\n')
        scan(self.db, self.c)
        self.assertEqual(events(self.db)[0]['code'], 'FUTURE-999')

    def test_no_code_oracle(self):
        self.write('R4MEAS,0,23,8,8,8,16,23,1\n' + FOOT)
        self.assertEqual(scan(self.db, self.c)['integrity']['code_verdict'], 'not_inferred')

    def test_testbench_record_patterns(self):
        self.write('PASS, all frames reported\nPASSIVE devices: 3\nFAILED to open file\nFAIL: frame 3\n' + FOOT)
        scan(self.db, self.c)
        kinds = [(e['raw'], e.get('problem_key')) for e in events(self.db) if e['category'] == 'testbench']
        self.assertEqual(kinds, [('PASS, all frames reported', None), ('FAIL: frame 3', 'TB:reported_FAIL')])

    def test_streams_and_generation_summary(self):
        self.write('WARNING (X-1): first\n    extra context\nWARNING (X-1): second\n'
                   'R4MEAS,0,23,8,8,8,16,23,1\nR4MEAS,1,24,8,8,8,16,24,0\n'
                   'R4MEAS,broken\nFAIL,explicit testbench report\n' + FOOT)
        scan(self.db, self.c)
        r = brief(self.db, 'test')
        self.assertEqual(r['problems']['printed_count'], 5)  # a continuation is not a problem
        self.assertEqual(r['measurements']['records'], 4)
        self.assertEqual(len(measurements(self.db, 'test')), 4)
        self.assertEqual([m['frame'] for m in measurements(self.db, 'test', tail=3) if 'frame' in m], [1])
        group = next(g for g in problem_groups(self.db, 'test') if g['problem_key'] == 'X-1')
        self.assertEqual(group['printed_count'], 2)
        self.assertEqual(evidence(self.db, group['first_evidence_id'])['cont'][0]['raw'], '    extra context')
        self.assertNotIn('fields_raw', json.dumps(events(self.db)))
        self.write(FOOT)
        scan(self.db, self.c)
        self.assertEqual(brief(self.db, 'test')['problems']['printed_count'], 0)
        self.assertEqual(len(problem_groups(self.db, 'test', generation=1)), 4)

    def test_measurement_paging(self):
        self.write(''.join(f'R4MEAS,{i},{i},8,8,8,16,{i},1\n' for i in range(10)) + FOOT)
        scan(self.db, self.c)
        tail = measurements(self.db, 'test', tail=3)
        self.assertEqual([m['frame'] for m in tail], [7, 8, 9])
        earlier = measurements(self.db, 'test', before=tail[0]['e'], limit=3)
        self.assertEqual([m['frame'] for m in earlier], [4, 5, 6])
        self.assertEqual([m['frame'] for m in measurements(self.db, 'test', limit=2)], [0, 1])

    def test_old_schema_is_rejected_untouched(self):
        old = self.p / 'old.sqlite'
        with sqlite3.connect(old) as raw:
            raw.execute('CREATE TABLE runs(id TEXT PRIMARY KEY, config TEXT, cursor TEXT, summary TEXT, updated REAL)')
        raw.close()
        before = hashlib.sha256(old.read_bytes()).hexdigest()
        with self.assertRaises(SchemaError):
            connect(old)
        with self.assertRaises(SchemaError):
            open_readonly(old)
        self.assertEqual(hashlib.sha256(old.read_bytes()).hexdigest(), before)
        with self.assertRaises(FileNotFoundError):
            open_readonly(self.p / 'missing.sqlite')
        self.assertFalse((self.p / 'missing.sqlite').exists())


